# -------------------------------
# Quad data (two triangles) with normals
# -------------------------------
# Quad in the XY plane, at z = -5
# We'll define four corners and two triangles (0-1-2 and 2-3-0)
quad_verts = [
    {'pos': [-1.0,  1.0, -5.0], 'normal': [0.0, 0.0, 1.0]},  # top-left
    {'pos': [ 1.0,  1.0, -5.0], 'normal': [0.0, 0.0, 1.0]},  # top-right
    {'pos': [ 1.0, -1.0, -5.0], 'normal': [0.0, 0.0, 1.0]},  # bottom-right
    {'pos': [-1.0, -1.0, -5.0], 'normal': [0.0, 0.0, 1.0]},  # bottom-left
]

# Indices for two triangles
quad_indices = [
    (0, 1, 2),
    (2, 3, 0),
]

# Uniforms (we'll rotate model around Y and X with mouse)
model = np.identity(4, dtype=np.float32)
view  = np.identity(4, dtype=np.float32)
proj  = np.identity(4, dtype=np.float32)

# Camera-ish projection
def update_projection(width, height):
    glMatrixMode(GL_PROJECTION)
    glLoadIdentity()
    aspect = width / float(height) if height > 0 else 1.0
    gluPerspective(45.0, aspect, 0.1, 100.0)
    glMatrixMode(GL_MODELVIEW)

# -------------------------------
# Optional: a tiny Jinja2-inspired per-vertex template
# This is illustrative; we compute in Python for reliability here.
# -------------------------------
template_src = """
# Vertex preface (generated by Jinja)
pos: {{ pos }}
normal: {{ normal }}

# Compute color from normal
color = [ (n[0]*0.5)+0.5, (n[1]*0.5)+0.5, (n[2]*0.5)+0.5 ]
"""
template = Template(template_src)

def render_vertex_with_template(v, mvp):
    # This demonstrates where you could render a template per-vertex.
    # For now, we compute directly; the template is shown for educational purposes.
    # Build a 4D pos
    p = v['pos'] + [1.0]
    # MVP-like transform: p' = MVP * p
    # Compute using numpy for accuracy
    gl_pos = (mvp @ np.array(p, dtype=np.float32)).tolist()
    # Color from normal
    n = np.array(v['normal'], dtype=float)
    nm = np.linalg.norm(n)
    if nm != 0:
        n_norm = (n / nm).tolist()
    else:
        n_norm = n.tolist()
    color = [(n_norm[0]*0.5)+0.5, (n_norm[1]*0.5)+0.5, (n_norm[2]*0.5)+0.5]
    return {'gl_pos': gl_pos, 'color': color}

# -------------------------------
# Interaction: mouse-driven rotation
# -------------------------------
rot_x, rot_y = 0.0, 0.0
dragging = False
last_x, last_y = 0, 0

def mouse(button, state, x, y):
    global dragging, last_x, last_y
    if button == GLUT_LEFT_BUTTON:
        if state == GLUT_DOWN:
            dragging = True
            last_x, last_y = x, y
        else:
            dragging = False

def motion(x, y):
    global rot_x, rot_y, last_x, last_y
    if dragging:
        dx = x - last_x
        dy = y - last_y
        last_x, last_y = x, y
        # Update rotation angles (sensitivity)
        rot_y += dx * 0.5
        rot_x += dy * 0.5
        glutPostRedisplay()

