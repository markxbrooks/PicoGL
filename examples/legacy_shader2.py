# -------------------------------
# OpenGL setup and render loop
# -------------------------------
def init_gl():
    glClearColor(0.15, 0.15, 0.2, 1.0)
    glEnable(GL_DEPTH_TEST)
    glShadeModel(GL_SMOOTH)

def display():
    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT)
    glLoadIdentity()

    # Simple camera: place back a bit and apply rotations
    glTranslatef(0.0, 0.0, -8.0)

    # Apply rotations from mouse
    glRotatef(rot_x, 1.0, 0.0, 0.0)
    glRotatef(rot_y, 0.0, 1.0, 0.0)

    # Optional: emulate "MVP" by building a model-view-projection using fixed-function
    # Since we're using fixed-function, we just rely on these transforms above.

    # Compute per-vertex outputs (CPU-side)
    # We create mvp for demonstration (identity here plus the above transforms)
    # In this simple demo, we'll just use the pre-transforms by OpenGL.
    # We'll still compute a color per vertex from their normals.

    glBegin(GL_TRIANGLES)
    for idx in quad_indices:
        for i in idx:
            v = quad_verts[i]
            # Compute color from normal (same as CPU)
            n = np.array(v['normal'], dtype=float)
            nm = np.linalg.norm(n)
            if nm != 0:
                n_norm = (n / nm).tolist()
            else:
                n_norm = n.tolist()
            color = [(n_norm[0]*0.5)+0.5, (n_norm[1]*0.5)+0.5, (n_norm[2]*0.5)+0.5]
            glColor3f(*color)
            glVertex3f(v['pos'][0], v['pos'][1], v['pos'][2])
    glEnd()

    glutSwapBuffers()

def reshape(width, height):
    if height == 0:
        height = 1
    glViewport(0, 0, width, height)
    glMatrixMode(GL_PROJECTION)
    glLoadIdentity()
    aspect = width / float(height)
    gluPerspective(45.0, aspect, 0.1, 100.0)
    glMatrixMode(GL_MODELVIEW)
    glLoadIdentity()

def main():
    glutInit(sys.argv)
    glutInitDisplayMode(GLUT_DOUBLE | GLUT_RGBA | GLUT_DEPTH)
    glutInitWindowSize(800, 600)
    glutCreateWindow(b"Quad with mouse rotation - PyOpenGL + GLUT (legacy GL)")

    init_gl()
    glutDisplayFunc(display)
    glutReshapeFunc(reshape)
    glutMouseFunc(mouse)
    glutMotionFunc(motion)
    glutKeyboardFunc(keyboard)

    # Initial projection setup (in reshape)
    glutMainLoop()

if __name__ == "__main__":
    main()
